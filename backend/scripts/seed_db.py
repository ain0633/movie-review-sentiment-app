def main():
    health = httpx.get(f"{BASE}/health", timeout=5).json()
    assert health["model_loaded"], "백엔드를 먼저 실행하세요 (모델 로드 포함)"

    for m in MOVIES:
        reviews = m.pop("reviews")
        movie = httpx.post(f"{BASE}/movies", json=m, timeout=30).json()
        pos = neg = 0
        for author, content in reviews:
            r = httpx.post(f"{BASE}/reviews", json={
                "movie_id": movie["id"], "author": author, "content": content}, timeout=30).json()
            if r["sentiment_label"] == "positive":
                pos += 1
            else:
                neg += 1
        rating = httpx.get(f"{BASE}/movies/{movie['id']}/rating", timeout=10).json()
        print(f"{movie['title']}: 리뷰 {pos + neg}개 (긍정 {pos}/부정 {neg}) "
              f"→ 평점 {rating['avg_score']:.3f} (★{rating['avg_score'] * 5:.1f})")

    total = len(httpx.get(f"{BASE}/reviews", params={"limit": 500}, timeout=10).json())
    print(f"완료: 영화 {len(MOVIES)}개, 리뷰 총 {total}개")


if __name__ == "__main__":
    main()
